function pickDescription(title) {
  const lower = title.trim().toLowerCase();
  for (const [needle, text] of DESCRIPTION_BY_TITLE) {
    if (lower.includes(needle)) return text;
  }
  return null;
}

const sql = postgres(url, { max: 1 });

try {
  const rows = await sql`
    SELECT id, title
    FROM anime
    WHERE description IS NULL OR btrim(description) = ''
    ORDER BY id
  `;

  if (!rows.length) {
    console.log("OK: all anime already have descriptions.");
    process.exit(0);
  }

  let updated = 0;
  let skipped = 0;

  for (const row of rows) {
    const text = pickDescription(row.title);
    if (!text) {
      skipped++;
      console.log(`SKIP (no template): #${row.id} ${row.title}`);
      continue;
    }
    await sql`
      UPDATE anime
      SET description = ${text}
      WHERE id = ${row.id}
    `;
    updated++;
    console.log(`UPDATED: #${row.id} ${row.title}`);
  }

  console.log(`Done: ${updated} updated, ${skipped} without template.`);
} catch (err) {
  console.error(err);
  process.exit(1);
} finally {
  await sql.end({ timeout: 5 });
}
